async function copyHtmlAndText(html, text) {
  try {
    if (window.ClipboardItem && navigator.clipboard && navigator.clipboard.write) {
      const hb = new Blob([html], { type: 'text/html' });
      const tb = new Blob([text], { type: 'text/plain' });
      await navigator.clipboard.write([new ClipboardItem({ 'text/html': hb, 'text/plain': tb })]);
      return true;
    }
  } catch (e) {}
  try { await navigator.clipboard.writeText(text); return true; } catch (e) {}
  return false;
}

function formatLongDate(s) {
  if (!s) return '';
  const d = new Date(s);
  if (isNaN(d.getTime())) return '';
  return d.toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' });
}

/**
 * Register an email-template native module. Each template plugs into the same shell:
 * meta strip at top, form on the left, sticky preview on the right with Generate/Clear/Copy.
 *
 * opts = {
 *   title, desc, icon,
 *   sendTo, copyTo, note,             // optional meta strip
 *   hasSubject (bool),                // shows a subject line above the preview body
 *   formHTML (string),                // raw form fields HTML
 *   onGenerate(formEl) → { subject?, body },  // returns the rendered email
 *   applyDefaults(formEl)?,           // called on mount + after clear
 *   onMount(formEl, container)?       // wire up extra interactive bits (dynamic field adds etc.)
 * }
 */
function buildEmailTemplate(slug, opts) {
  TOOL_MODULES[slug] = {
    title: opts.title,
    desc: opts.desc,
    icon: opts.icon || 'mail',
    render(container) {
      container.innerHTML = `
        <div class="tpl-tool">
          ${(opts.sendTo || opts.copyTo || opts.note) ? `
            <div class="tpl-meta">
              ${opts.sendTo ? `<div><span class="tpl-meta-label">Send to</span><code>${opts.sendTo}</code></div>` : ''}
              ${opts.copyTo ? `<div><span class="tpl-meta-label">Copy</span><span>${opts.copyTo}</span></div>` : ''}
              ${opts.note ? `<p class="tpl-meta-note">${opts.note}</p>` : ''}
            </div>
          ` : ''}

          <div class="tpl-grid">
            <form class="tpl-form" data-tpl-form>
              ${opts.formHTML}
              <div class="tpl-actions">
                <button type="button" class="btn" data-tpl-act="clear">Clear fields</button>
                <button type="submit" class="btn btn-primary">Generate email</button>
              </div>
            </form>

            <aside class="tpl-preview">
              <div class="tpl-preview-head">
                <span>Email preview</span>
                <div class="tpl-copy-group">
                  ${opts.hasSubject ? `<button type="button" class="btn-ghost" data-tpl-act="copy-subject" disabled>${svgIcon('link', 14)} Subject</button>` : ''}
                  <button type="button" class="btn-ghost" data-tpl-act="copy-body" disabled>${svgIcon('link', 14)} Body</button>
                </div>
              </div>
              ${opts.hasSubject ? '<div class="tpl-subject" data-tpl-subject></div>' : ''}
              <div class="tpl-preview-body" data-tpl-body>
                <p class="tpl-empty">Fill the form and click <strong>Generate email</strong>.</p>
              </div>
              <div class="tpl-flash" data-tpl-flash></div>
            </aside>
          </div>
        </div>
      `;

      const form         = container.querySelector('[data-tpl-form]');
      const body         = container.querySelector('[data-tpl-body]');
      const subject      = container.querySelector('[data-tpl-subject]');
      const flashEl      = container.querySelector('[data-tpl-flash]');
      const copyBodyBtn  = container.querySelector('[data-tpl-act="copy-body"]');
      const copySubBtn   = container.querySelector('[data-tpl-act="copy-subject"]');
      const clearBtn     = container.querySelector('[data-tpl-act="clear"]');

      let flashTimer = null;
      const flash = (msg) => {
        flashEl.textContent = msg;
        flashEl.classList.add('show');
        clearTimeout(flashTimer);
        flashTimer = setTimeout(() => flashEl.classList.remove('show'), 2200);
      };

      const resetPreview = () => {
        body.innerHTML = `<p class="tpl-empty">Fill the form and click <strong>Generate email</strong>.</p>`;
        if (subject) subject.textContent = '';
        copyBodyBtn.disabled = true;
        if (copySubBtn) copySubBtn.disabled = true;
      };

      form.addEventListener('submit', e => {
        e.preventDefault();
        const result = opts.onGenerate(form);
        if (!result) { flash('Please fill in the required fields.'); return; }
        body.innerHTML = result.body || '';
        if (subject && result.subject != null) subject.textContent = result.subject;
        copyBodyBtn.disabled = !result.body;
        if (copySubBtn) copySubBtn.disabled = !result.subject;
        flash('Email generated.');
      });

      clearBtn.addEventListener('click', () => {
        form.reset();
        if (opts.applyDefaults) opts.applyDefaults(form);
        resetPreview();
        flash('Fields cleared.');
      });

      copyBodyBtn.addEventListener('click', async () => {
        const ok = await copyHtmlAndText(body.innerHTML, body.innerText);
        flash(ok ? 'Email body copied.' : 'Copy failed — select manually.');
      });

      if (copySubBtn) {
        copySubBtn.addEventListener('click', async () => {
          if (!subject.textContent) return;
          try { await navigator.clipboard.writeText(subject.textContent); flash('Subject copied.'); }
          catch (e) { flash('Copy failed.'); }
        });
      }

      if (opts.applyDefaults) opts.applyDefaults(form);
      if (opts.onMount) opts.onMount(form, container);
    }
  };
}

