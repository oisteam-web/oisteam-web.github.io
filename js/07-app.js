(function initDrawer() {
  const btn = document.getElementById('menu-toggle');
  const side = document.getElementById('sidebar');
  const scrim = document.getElementById('scrim');
  if (!btn || !side || !scrim) return;
  btn.setAttribute('aria-controls', 'sidebar');
  btn.setAttribute('aria-expanded', 'false');
  const set = open => {
    side.classList.toggle('open', open);
    scrim.classList.toggle('open', open);
    document.body.classList.toggle('drawer-open', open);
    btn.setAttribute('aria-expanded', String(open));
    btn.setAttribute('aria-label', open ? 'Close navigation' : 'Open navigation');
  };
  btn.addEventListener('click', () => set(!side.classList.contains('open')));
  scrim.addEventListener('click', () => set(false));
  document.addEventListener('keydown', e => { if (e.key === 'Escape' && side.classList.contains('open')) set(false); });
  // Picking a page closes the drawer; section headings don't.
  side.addEventListener('click', e => { if (e.target.closest('.nav-item')) set(false); });
  matchMedia('(min-width: 769px)').addEventListener('change', e => { if (e.matches) set(false); });
})();

function setActiveNav(routeKey) {
  document.querySelectorAll('.nav-item').forEach(n => {
    const on = n.dataset.route === routeKey;
    n.classList.toggle('active', on);
    // Never hide the page you're on: open its section if it was collapsed.
    const sec = on && n.closest('.sidebar-section.is-collapsed');
    if (sec) { sec.classList.remove('is-collapsed'); sec.querySelector('.sidebar-toggle')?.setAttribute('aria-expanded', 'true'); }
  });
}

