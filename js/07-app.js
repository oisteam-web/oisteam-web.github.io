// ─── JARVIS: Animated typing placeholder ────────────────
(function() {
  const input = document.getElementById('search');
  if (!input) return;
  const phrases = [
    'Search tools, paste a name…',
    'Try "banner generator"…',
    'Try "CCM exporter"…',
    'Try "mockup"…',
    'Try "helpdesk"…',
    'One page to open everything.',
  ];
  let pi = 0, ci = 0, deleting = false, paused = false;
  function type() {
    if (document.activeElement === input) { setTimeout(type, 300); return; }
    const phrase = phrases[pi];
    if (!deleting) {
      input.placeholder = phrase.slice(0, ++ci);
      if (ci === phrase.length) { paused = true; deleting = true; setTimeout(type, 1800); return; }
      setTimeout(type, 55);
    } else {
      input.placeholder = phrase.slice(0, --ci);
      if (ci === 0) { deleting = false; pi = (pi + 1) % phrases.length; setTimeout(type, 400); return; }
      setTimeout(type, 28);
    }
  }
  setTimeout(type, 2200); // start after boot splash
})();

// ─── JARVIS: 3D tilt on cards ───────────────────────────
(function() {
  function attachTilt(card) {
    card.addEventListener('mousemove', e => {
      const r = card.getBoundingClientRect();
      const x = e.clientX - r.left, y = e.clientY - r.top;
      const cx = r.width / 2, cy = r.height / 2;
      const rotX = ((y - cy) / cy) * -8;
      const rotY = ((x - cx) / cx) * 8;
      card.style.transform = `translateY(-3px) scale(1.01) perspective(600px) rotateX(${rotX}deg) rotateY(${rotY}deg)`;
      card.style.setProperty('--mx', x + 'px');
      card.style.setProperty('--my', y + 'px');
    });
    card.addEventListener('mouseleave', () => {
      card.style.transform = '';
    });
  }
  function initTilts() {
    document.querySelectorAll('.card:not(.card-add)').forEach(attachTilt);
  }
  // Re-attach after any render
  const observer = new MutationObserver(() => initTilts());
  const content = document.getElementById('content');
  if (content) observer.observe(content, { childList: true, subtree: true });
  initTilts();
})();
