function classifyLink(url) {
  try {
    const h = new URL(url).hostname;
    if (h.includes('docs.google.com')) {
      if (url.includes('/spreadsheets/')) return { type: 'Google Sheet',     host: h, icon: 'chart-bar' };
      if (url.includes('/document/'))     return { type: 'Google Doc',       host: h, icon: 'book-2'    };
      if (url.includes('/presentation/')) return { type: 'Google Slides',    host: h, icon: 'layout-grid' };
      return { type: 'Google Workspace', host: h, icon: 'book-2' };
    }
    if (h.includes('drive.google.com'))                return { type: 'Drive folder',  host: h, icon: 'database' };
    if (h.includes('lightning.force.com') || h.includes('salesforce'))
                                                       return { type: 'Salesforce',    host: h, icon: 'shield' };
    if (h.includes('trustarc.com') || h.includes('truste-svc.net'))
                                                       return { type: 'TrustArc',      host: h, icon: 'shield' };
    return { type: 'External link', host: h, icon: 'link' };
  } catch (e) {
    return { type: 'Link', host: '', icon: 'link' };
  }
}

