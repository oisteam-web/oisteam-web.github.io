// ─── Order persistence ───────────────────────────────────
const ORDER_KEY = 'ois-hub-order-v1';

// Only categories that actually render on the home grid can be dragged, so
// only those should have their order persisted. Sidebar-only / hidden
// categories must always follow the order defined in DEFAULT_TOOLS — otherwise
// a stale saved order silently overrides a reorder shipped in the code.
const isReorderable = cat => !cat.sidebarOnly && cat.category !== 'Quicklinks';

function loadOrder() {
  let saved;
  try { saved = JSON.parse(localStorage.getItem(ORDER_KEY)); } catch (e) { return; }
  if (!saved || typeof saved !== 'object') return;
  TOOLS.forEach((cat, ci) => {
    if (!isReorderable(cat)) return;
    const ord = saved[cat.category];
    if (!Array.isArray(ord)) return;
    const defaults = DEFAULT_TOOLS[ci] && DEFAULT_TOOLS[ci].category === cat.category
      ? DEFAULT_TOOLS[ci].items.map(t => t.name) : [];

    // Items the user has already arranged, in their saved order.
    const known = cat.items.filter(t => ord.indexOf(t.name) !== -1)
                           .sort((a, b) => ord.indexOf(a.name) - ord.indexOf(b.name));
    // Items added since that order was saved. Splice each in at its DEFAULT
    // index rather than dumping it at the end, so a new tool shipped at the top
    // of a category still shows up at the top for existing users.
    cat.items.filter(t => ord.indexOf(t.name) === -1)
             .sort((a, b) => defaults.indexOf(a.name) - defaults.indexOf(b.name))
             .forEach(t => {
               const at = defaults.indexOf(t.name);
               known.splice(at === -1 ? known.length : Math.min(at, known.length), 0, t);
             });
    cat.items = known;
  });
}

function saveOrder() {
  const order = {};
  TOOLS.forEach(cat => {
    if (!isReorderable(cat)) return;   // never persist non-draggable categories
    order[cat.category] = cat.items.map(t => t.name);
  });
  localStorage.setItem(ORDER_KEY, JSON.stringify(order));
}

