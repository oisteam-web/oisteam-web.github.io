    const extCount = cat.items.filter(t => t.type === 'extension').length;
    const isCompact = extCount > cat.items.length / 2;
    // Default type for the "+ Add" button — match the majority type of the category
    const typeCounts = cat.items.reduce((acc, t) => { acc[t.type] = (acc[t.type] || 0) + 1; return acc; }, {});
