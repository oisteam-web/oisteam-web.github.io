function parseHash() {
  const h = (location.hash || '').replace(/^#/, '');
  if (!h || h === 'home') return { view: 'home' };
  const params = new URLSearchParams(h);
  if (params.has('tool')) return { view: 'tool', tool: params.get('tool') };
  if (params.has('ext'))  return { view: 'external', tool: params.get('ext') };
  return { view: 'home' };
}

