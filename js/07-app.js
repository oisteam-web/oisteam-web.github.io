const SIDEBAR_COLLAPSE_KEY = 'ois-hub-sidebar-collapsed';
const sidebarCollapsed = new Set((() => { try { return JSON.parse(localStorage.getItem(SIDEBAR_COLLAPSE_KEY)) || []; } catch (_) { return []; } })());

function renderSidebar() {
  const wrap = document.getElementById('sidebar-tools');
  if (!wrap) return;
  wrap.innerHTML = TOOLS.filter(c => c.items.length && c.category !== 'Quicklinks').map(cat => {
    const items = cat.items.filter(t => !t.hidden).map(t => {
      const target = t.native ? `tool=${t.native}` : `ext=${encodeURIComponent(t.name)}`;
      const isExternal = !t.native && t.url && t.url !== '#';
      const soon = !!t.comingSoon;
      // Inert only when there's genuinely nowhere to go. Tips and Tricks is
      // flagged "soon" but has a real page (with its own overlay), so it stays
      // clickable; the extensions have no destination yet, so they don't.
      const inert = soon && !t.native && !isExternal;
      // Only the Soon tag survives — Native / EXT / LINK were visual noise.
      const tagHTML = soon ? `<span class="nav-tag nav-tag-soon">Soon</span>` : '';
      // Names are ellipsised in the sidebar, so always expose the full one.
      const full = t.name + (isExternal ? ' (opens in a new tab)' : (soon ? ' — coming soon' : ''));
      const a11y = ` title="${esc(full)}" aria-label="${esc(full)}"`
                 + (inert ? ' aria-disabled="true" disabled' : '');
      return `
        <button class="nav-item${soon ? ' is-soon' : ''}" data-route="${target}" data-name="${esc(t.name)}"${a11y}>
          <span class="nav-icon icon-${t.color}" style="color:var(--${t.color})">${svgIcon(t.icon, 16)}</span>
          <span class="nav-name">${esc(t.sidebarName || t.name)}</span>
          ${tagHTML}
        </button>
      `;
    }).join('');
    const closed = sidebarCollapsed.has(cat.category);
    return `
      <div class="sidebar-section${closed ? ' is-collapsed' : ''}" data-cat="${esc(cat.category)}">
        <button type="button" class="sidebar-label sidebar-toggle" aria-expanded="${!closed}">
          <span>${esc(cat.category)}</span>
          <svg class="sidebar-chevron" width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="m6 9 6 6 6-6"/></svg>
        </button>
        <div class="sidebar-items"><div>${items}</div></div>
      </div>
    `;
  }).join('');
  if (!wrap.dataset.toggleBound) {
    wrap.dataset.toggleBound = '1';
    wrap.addEventListener('click', e => {
      const btn = e.target.closest('.sidebar-toggle');
      if (!btn) return;
      const sec = btn.parentElement;
      const closed = sec.classList.toggle('is-collapsed');
      btn.setAttribute('aria-expanded', String(!closed));
      closed ? sidebarCollapsed.add(sec.dataset.cat) : sidebarCollapsed.delete(sec.dataset.cat);
      try { localStorage.setItem(SIDEBAR_COLLAPSE_KEY, JSON.stringify([...sidebarCollapsed])); } catch (_) {}
    });
  }
}

