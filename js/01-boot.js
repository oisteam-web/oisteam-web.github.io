  var el  = document.getElementById('jarvis-boot');
  var bar = document.getElementById('boot-bar');
  if (!el) return;
  requestAnimationFrame(function () { bar.style.width = '100%'; });
  setTimeout(function () {
    el.style.animation = 'boot-fade-out .35s ease forwards';
    setTimeout(function () { el.style.display = 'none'; }, 350);
  }, 420);
