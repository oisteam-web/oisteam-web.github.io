    function copyCurrentCode() {
        const codeContent = document.getElementById('code-view-content').textContent;
        if (!codeContent) {
            showModal('Nothing to copy. Please generate a script first.');
            return;
        }
        navigator.clipboard.writeText(codeContent).then(() => {
            const originalText = copyCodeBtn.textContent;
            copyCodeBtn.textContent = 'Copied!';
            setTimeout(() => { copyCodeBtn.textContent = originalText; }, 2000);
        }).catch(err => {
            console.error('Could not copy text: ', err);
            showModal('Failed to copy text to clipboard.');
        });
    }

    function saveCurrentCode() {
        const htmlContent = document.getElementById('code-view-content').textContent;
        if (!htmlContent || activeMockupIndex < 0) {
            showModal('Nothing to save. Please generate a script first.');
            return;
        }

        const cmDomain = document.getElementById('cmDomain').value;
        const mockupDescFilename = document.getElementById(`mockupDesc${activeMockupIndex}`).value || `mockup_${activeMockupIndex}`;
        const ccmProduct = document.getElementById('ccmProduct').value;
        const cmId = document.getElementById('cmId')?.value || '';

        const fileName = `${cmId || cmDomain}_${formatString(mockupDescFilename)}_${ccmProduct}_mockup.html`;
        const blob = new Blob([htmlContent], { type: 'text/html' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = fileName;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
    }

    function generateHtmlLinks(currentIndex, delimiter = '\n') {
        const ccmProduct = document.getElementById('ccmProduct').value;
        const cmDomain = document.getElementById('cmDomain').value;
        const cmId = document.getElementById('cmId')?.value || '';
        let linksArray = [];
        document.querySelectorAll('.file-input-card').forEach((card) => {
            const index = parseInt(card.dataset.index, 10);
            const mockupDesc = document.getElementById(`mockupDesc${index}`).value || `Mockup ${index + 1}`;
            const href = `${cmId || cmDomain}_${formatString(mockupDesc)}_${ccmProduct}_mockup.html`;
            linksArray.push(index === currentIndex ? `<b>${mockupDesc}</b>` : `<a href="${href}">${mockupDesc}</a>`);
        });
        return linksArray.join(delimiter);
    }

    function formatString(str) {
        return str
          .toLowerCase()
          .trim()
          .replace(/[^\w\s]/gi, '') 
          .replace(/\s+/g, '_');
      }
    
    async function exportAllAsZip() {
        const clientName = document.getElementById('clientName').value;
        const cmDomain = document.getElementById('cmDomain').value;
        const ccmProduct = document.getElementById('ccmProduct').value;
        const cmId = document.getElementById('cmId')?.value || '';
        const cmProInstance = document.getElementById('cmProInstance')?.value || '';

        if ((ccmProduct === 'ccmpro' && (!cmId || !cmProInstance)) || (ccmProduct === 'ccmadv' && !cmDomain) || !clientName) {
            showModal('Please fill in all required global fields before exporting.');
            return;
        }

        const zip = new JSZip();
        const cards = document.querySelectorAll('.file-input-card');
        let filesAdded = 0;

        if (cards.length === 0) {
            showModal('No files to export.');
            return;
        }

        cards.forEach(card => {
            const index = parseInt(card.dataset.index, 10);
            const htmlContent = getMockupHTML(index);
            if (htmlContent) {
                const descShorthand = document.getElementById(`mockupDesc${index}`).value || `mockup_${index}`;
                const fileName = `${cmId || cmDomain}_${formatString(descShorthand)}_${ccmProduct}_mockup.html`;
                zip.file(fileName, htmlContent);
                filesAdded++;
            }
        });

        if (filesAdded === 0) {
            showModal('Could not generate any files. Check your configuration.');
            return;
        }

        const content = await zip.generateAsync({type: 'blob'});
        const url = URL.createObjectURL(content);
        const a = document.createElement('a');
        a.href = url;
        a.download = `${cmId || cmDomain}_mockups.zip`;
        document.body.appendChild(a);
        a.click();
        
        setTimeout(() => {
            document.body.removeChild(a);
            URL.revokeObjectURL(url);
        }, 100);
    }

    function showModal(message) {
        // First, remove any existing modal
        const existingOverlay = document.querySelector('.modal-overlay');
        if (existingOverlay) {
            existingOverlay.remove();
        }

        const overlay = document.createElement('div');
        overlay.className = 'modal-overlay'; // Add a class for easier removal
        overlay.style.cssText = 'position:fixed; top:0; left:0; width:100%; height:100%; background:rgba(0,0,0,0.5); z-index:9998;';
        
        const alertBox = document.createElement('div');
        alertBox.style.cssText = 'position:fixed; top:50%; left:50%; transform:translate(-50%, -50%); padding:20px; background:#fff; color:#000; border-radius:5px; z-index:9999; text-align:center;';
        alertBox.innerHTML = `<p>${message}</p><button id="okButton" style="margin-top:15px;">OK</button>`;
        
        overlay.appendChild(alertBox);
        document.body.appendChild(overlay);

        const okBtn = document.getElementById('okButton');
        okBtn.focus();
        okBtn.onclick = () => {
            document.body.removeChild(overlay);
        };
    }

