async function applyBlueFillsViaXML(buffer, exportedCells, firstLocaleColNum, headerRowNum, sectionHeaderRows) {
    if (exportedCells.size === 0) return buffer;

    const zip = await JSZip.loadAsync(buffer);

    const relsXml   = await zip.file('xl/_rels/workbook.xml.rels').async('text');
    const wbXml     = await zip.file('xl/workbook.xml').async('text');
    const rIdToPath = {};
    for (const m of relsXml.matchAll(/Id="([^"]+)"[^>]+Target="([^"]+)"/g)) {
        rIdToPath[m[1]] = m[2];
    }
    const sheetIdMatch = wbXml.match(/<sheet [^>]*r:id="([^"]+)"/);
    if (!sheetIdMatch) return buffer;
    let sheetPath = rIdToPath[sheetIdMatch[1]] || '';
    if (!sheetPath.startsWith('xl/')) sheetPath = 'xl/' + sheetPath;

    let stylesXml = await zip.file('xl/styles.xml').async('text');

    const fillCountM = stylesXml.match(/<fills count="(\d+)"/);
    const fillCount  = fillCountM ? parseInt(fillCountM[1]) : 2;
    const blueFillId = fillCount;

    stylesXml = stylesXml
        .replace(/<fills count="\d+"/, `<fills count="${fillCount + 1}"`)
        .replace('</fills>',
            `<fill><patternFill patternType="solid"><fgColor rgb="FFA4C2F4"/><bgColor indexed="64"/></patternFill></fill></fills>`);

    const xfsCountM = stylesXml.match(/<cellXfs count="(\d+)"/);
    const xfsCount  = xfsCountM ? parseInt(xfsCountM[1]) : 1;
    const blueXfId  = xfsCount;

    stylesXml = stylesXml
        .replace(/<cellXfs count="\d+"/, `<cellXfs count="${xfsCount + 1}"`)
        .replace('</cellXfs>',
            `<xf numFmtId="0" fontId="0" fillId="${blueFillId}" borderId="0" xfId="0" applyFill="1"/></cellXfs>`);

    zip.file('xl/styles.xml', stylesXml);

    let sheetXml    = await zip.file(sheetPath).async('text');
    let updateCount = 0;

    for (const cellKey of exportedCells) {
        const parts  = cellKey.split('_');
        const rowNum = parseInt(parts[0]);
        const colNum = parseInt(parts[1]);
        if (rowNum <= headerRowNum || sectionHeaderRows.has(rowNum) || colNum < firstLocaleColNum) continue;

        const addr = numToCol(colNum) + rowNum;
        const re   = new RegExp('(<c r="' + addr + '")(\\s[^>]*)?(>)', 'g');
        const prev = sheetXml;

        sheetXml = sheetXml.replace(re, function(match, start, attrs, end) {
            const clean = (attrs || '').replace(/\s+s="[^"]*"/, '');
            return start + clean + ' s="' + blueXfId + '"' + end;
        });

        if (sheetXml !== prev) updateCount++;
    }

    zip.file(sheetPath, sheetXml);
    window._xmlBlueCellCount = updateCount;
    return zip.generateAsync({ type: 'arraybuffer' });
}

