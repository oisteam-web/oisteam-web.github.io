// ════════════════════════════════════════════════════════════
//  PARSE RAW EXPORT
// ════════════════════════════════════════════════════════════
function parseRaw(raw, localeMap) {
    const lines   = raw.trim().split(/\r?\n/);
    const records = [];
    const skippedLocales = new Set();

    for (const line of lines) {
        if (!line.trim()) continue;
        const cols = line.split('\t');
        if (cols.length < 4) continue;
        const [type, locale, key, ...rest] = cols.map(c => c.trim());
        const translation = rest.join('\t').trim();
        if (locale.toLowerCase() === 'locale' || key.toLowerCase() === 'key') continue;
        if (!locale || !key) continue;
        records.push({ type, locale, key, translation });
        if (!(locale in localeMap)) skippedLocales.add(locale);
    }

    return { records, skippedLocales: [...skippedLocales] };
}

