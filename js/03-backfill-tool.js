async function mergeAndGenerate() {
    if (!uploadedWorkbook) {
        showStatus('⚠ Please upload the Standard Template first (Step 1).', 'error');
        return;
    }
    const raw = document.getElementById('rawData').value;
    if (!raw.trim()) {
        showStatus('⚠ Please paste the raw export data first (Step 2).', 'error');
        return;
    }

    const config = uploadedSheetType === 'slider' ? SLIDER : GRANULAR;
    const label  = uploadedSheetType === 'slider' ? 'Slider' : 'Granular';

    const btn = document.getElementById('mergeBtn');
    btn.disabled = true;
    btn.innerHTML = '<svg width="14" height="14" viewBox="0 0 14 14" fill="none" style="animation:spin 0.8s linear infinite"><circle cx="7" cy="7" r="5" stroke="rgba(255,255,255,0.35)" stroke-width="2"/><path d="M7 2a5 5 0 015 5" stroke="white" stroke-width="2" stroke-linecap="round"/></svg>&nbsp; Generating…';

    showStatus('⏳ Merging data into <strong>' + label + ' OverlayType</strong> template…', 'info');

    try {
        const { records, skippedLocales } = parseRaw(raw, config.localeMap);
        if (records.length === 0) {
            showStatus('❌ No valid data found. Check columns: Type · Locale · Key · Translation', 'error');
            return;
        }

        let ws = null;
        uploadedWorkbook.worksheets.forEach(sheet => {
            const n = sheet.name.toLowerCase();
            if (uploadedSheetType === 'slider'   && n.includes('slider'))   ws = sheet;
            if (uploadedSheetType === 'granular' && n.includes('granular')) ws = sheet;
        });
        if (!ws) ws = uploadedWorkbook.getWorksheet(1);

        const cellText = v => {
            if (!v && v !== 0) return '';
            if (typeof v === 'string') return v.trim();
            if (typeof v === 'object') {
                if (v.richText) return v.richText.map(r => r.text || '').join('').trim();
                if (v.result !== undefined) return String(v.result).trim();
                if (v.text) return String(v.text).trim();
            }
            return String(v).trim();
        };

        let headerRowNum = 5, defaultVerbiageCol = 1;
        ws.eachRow((row, rn) => {
            row.eachCell((cell, colNum) => {
                if (cellText(cell.value) === 'Default Verbiage (en)') {
                    headerRowNum       = rn;
                    defaultVerbiageCol = colNum;
                }
            });
        });

        const sectionHeaderRows = new Set();
        ws.eachRow((row, rowNum) => {
            if (rowNum <= headerRowNum) return;
            const aFill = row.getCell(1).fill;
            const argb  = aFill && aFill.fgColor && aFill.fgColor.argb ? aFill.fgColor.argb.toUpperCase() : '';
            if (argb === 'FF003A70') sectionHeaderRows.add(rowNum);
        });

        const localeColMap = {};
        ws.getRow(headerRowNum).eachCell((cell, colNum) => {
            const val = cellText(cell.value);
            if (!val) return;
            for (const [code, idx] of Object.entries(config.localeMap)) {
                if (config.headers[idx] === val) { localeColMap[code] = colNum; break; }
            }
        });

        const firstLocaleColNum = Object.keys(localeColMap).length > 0
            ? Math.min(...Object.values(localeColMap))
            : defaultVerbiageCol + 3;

        const exportLocalesInRaw = new Set(records.map(r => r.locale).filter(Boolean));
        const newLocalesList     = [...exportLocalesInRaw].filter(l => l && !localeColMap[l]);

        if (newLocalesList.length > 0) {
            const headerBg = uploadedSheetType === 'slider' ? 'FF1E6E4E' : 'FF1A3C6E';
            const localeHeaderName = {};
            for (const [code, idx] of Object.entries(GRANULAR.localeMap)) localeHeaderName[code] = GRANULAR.headers[idx];
            for (const [code, idx] of Object.entries(SLIDER.localeMap))   { if (!localeHeaderName[code]) localeHeaderName[code] = SLIDER.headers[idx]; }

            let lastLocaleCol = Object.values(localeColMap).length > 0
                ? Math.max(...Object.values(localeColMap))
                : defaultVerbiageCol + 3;

            for (const locale of newLocalesList) {
                lastLocaleCol++;
                localeColMap[locale]    = lastLocaleCol;
                const hCell             = ws.getRow(headerRowNum).getCell(lastLocaleCol);
                hCell.value             = localeHeaderName[locale] || locale;
                hCell.font              = { name: 'Arial', size: 10, bold: true, color: { argb: 'FFFFFFFF' } };
                hCell.fill              = { type: 'pattern', pattern: 'solid', fgColor: { argb: headerBg } };
                hCell.alignment         = { horizontal: 'left' };
                ws.getColumn(lastLocaleCol).width = 32;
            }
        }

        const keyRowMap = {};
        ws.eachRow((row, rowNum) => {
            if (rowNum <= headerRowNum)        return;
            if (sectionHeaderRows.has(rowNum)) return;
            const keyVal = cellText(row.getCell(defaultVerbiageCol).value);
            if (keyVal && !keyRowMap[keyVal]) keyRowMap[keyVal] = rowNum;
        });

        const exportMap = {};
        for (const { locale, key, translation } of records) {
            if (!exportMap[key]) exportMap[key] = {};
            exportMap[key][locale] = translation;
        }

        const templateFill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFB6D7A8' } };
        const exportFill   = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFA4C2F4' } };

        const exportedCells = new Set();
        let newRowsAdded = 0, cellsUpdated = 0;

        for (const [key, translations] of Object.entries(exportMap)) {
            let rowNum = keyRowMap[key];
            if (!rowNum) {
                const lastRowNum = ws.lastRow ? ws.lastRow.number + 1 : headerRowNum + 1;
                const newRow     = ws.getRow(lastRowNum);
                newRow.getCell(defaultVerbiageCol).value     = key;
                newRow.getCell(defaultVerbiageCol).font      = { name: 'Arial', size: 10 };
                newRow.getCell(defaultVerbiageCol).alignment = { wrapText: true, vertical: 'top' };
                exportedCells.add(lastRowNum + '_' + defaultVerbiageCol);
                rowNum = lastRowNum;
                keyRowMap[key] = rowNum;
                newRowsAdded++;
            }
            for (const [locale, translation] of Object.entries(translations)) {
                const colNum = localeColMap[locale];
                if (!colNum || !translation) continue;
                const cell       = ws.getRow(rowNum).getCell(colNum);
                cell.value       = translation;
                cell.fill        = exportFill;
                if (!cell.font)      cell.font      = { name: 'Arial', size: 10 };
                if (!cell.alignment) cell.alignment = { wrapText: true, vertical: 'top' };
                exportedCells.add(rowNum + '_' + colNum);
                cellsUpdated++;
            }
        }

        ws.eachRow((row, rowNum) => {
            if (rowNum <= headerRowNum)        return;
            if (sectionHeaderRows.has(rowNum)) return;
            row.eachCell((cell, colNum) => {
                if (colNum < firstLocaleColNum)               return;
                if (exportedCells.has(rowNum + '_' + colNum)) return;
                const v = cell.value;
                if (v !== null && v !== undefined && v !== '') cell.fill = templateFill;
            });
        });

        const clientType = (records[0].type || 'Client').replace(/[^a-zA-Z0-9]/g, '_');
        const today      = new Date().toISOString().split('T')[0];
        const filename   = 'OIS_Translation_Merged_' + label + '_' + clientType + '_' + today + '.xlsx';

        let buffer = await uploadedWorkbook.xlsx.writeBuffer();
        buffer     = await applyBlueFillsViaXML(buffer, exportedCells, firstLocaleColNum, headerRowNum, sectionHeaderRows);

        const blob = new Blob([buffer], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
        const url  = URL.createObjectURL(blob);
        const a    = document.createElement('a');
        a.href = url; a.download = filename; a.click();
        URL.revokeObjectURL(url);

        const trulySkipped = skippedLocales.filter(l => !localeColMap[l]);
        const xmlBlueCount = window._xmlBlueCellCount || 0;
        const addedMsg  = newLocalesList.length > 0 ? ' &nbsp;|&nbsp; ➕ New columns: ' + newLocalesList.join(', ') : '';
        const skipMsg   = trulySkipped.length > 0   ? ' &nbsp;|&nbsp; ⚠ Skipped: ' + trulySkipped.join(', ') : '';
        const newRowMsg = newRowsAdded > 0           ? ' &nbsp;|&nbsp; ' + newRowsAdded + ' new row(s) added' : '';

        showStatus(
            '✅ <strong>Downloaded:</strong> ' + filename +
            ' &nbsp;|&nbsp; ' + cellsUpdated + ' cells merged' +
            ' &nbsp;|&nbsp; 🟢 Template &nbsp;🔵 Export (XML:' + xmlBlueCount + ')' +
            newRowMsg + addedMsg + skipMsg,
            'success'
        );

    } catch (err) {
        showStatus('❌ Error: ' + err.message, 'error');
        console.error(err);
    } finally {
        btn.disabled = false;
        btn.innerHTML =
            '<svg width="16" height="16" viewBox="0 0 16 16" fill="none">' +
            '<path d="M8 2v10" stroke="white" stroke-width="2" stroke-linecap="round"/>' +
            '<path d="M4 8.5L8 12.5L12 8.5" stroke="white" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>' +
            '<path d="M2 14.5h12" stroke="white" stroke-width="2" stroke-linecap="round"/>' +
            '</svg> Generate &amp; Merge';
    }
}

